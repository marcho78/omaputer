"""Generates lib/omarchy_menu/src/menu_fonts.h: JetBrains Mono at the sizes the tile menu
uses, as 4-bit anti-aliased glyph bitmaps for printable ASCII.

JetBrains Mono is under the SIL Open Font License 1.1 (see lib/omarchy_menu/OFL.txt).
Needs Pillow and the font installed (fc-match finds it).
Usage: python3 tools/make_menu_fonts.py
"""

import subprocess
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

OUT = Path(__file__).resolve().parent.parent / "lib/omarchy_menu/src/menu_fonts.h"
FONTS = [  # C name, fontconfig pattern, pixel size
    ("kFontSmall", "JetBrains Mono:style=Regular", 11),
    ("kFontBrand", "JetBrains Mono:style=Bold", 11),
    ("kFontLabel", "JetBrains Mono:style=Bold", 16),
]
FIRST, LAST = 32, 126


def font_file(pattern):
    return subprocess.run(["fc-match", "-f", "%{file}", pattern], capture_output=True, text=True, check=True).stdout


def render(name, pattern, size):
    font = ImageFont.truetype(font_file(pattern), size)
    ascent, descent = font.getmetrics()
    glyphs, bits = [], []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        advance = round(font.getlength(ch))
        x0, y0, x1, y1 = font.getbbox(ch)  # Relative to the top of the line (ascender).
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        offset = len(bits)
        if w and h:
            img = Image.new("L", (x1 + 2, y1 + 2), 0)
            ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
            img = img.crop((x0, y0, x1, y1))
            bits.extend((v + 8) // 17 for v in img.tobytes())  # 0..255 -> 0..15
        glyphs.append((offset, w, h, x0, y0, advance))
    # Pack two 4-bit pixels per byte, high nibble first.
    if len(bits) % 2:
        bits.append(0)
    packed = [(bits[i] << 4) | bits[i + 1] for i in range(0, len(bits), 2)]
    return name, pattern, size, ascent, descent, glyphs, packed


def main():
    parts = [
        "// Generated by tools/make_menu_fonts.py; do not edit.",
        "// JetBrains Mono (c) The JetBrains Mono Project Authors, SIL Open Font License 1.1.",
        "#pragma once",
        '#include "menu_font.h"',
        "",
        "namespace omenu {",
    ]
    for name, pattern, size, ascent, descent, glyphs, packed in map(lambda f: render(*f), FONTS):
        parts.append(f"// {pattern}, {size} px")
        parts.append(f"inline constexpr uint8_t {name}Bits[] = {{")
        for i in range(0, len(packed), 24):
            parts.append("    " + ", ".join(f"0x{b:02X}" for b in packed[i:i + 24]) + ",")
        parts.append("};")
        parts.append(f"inline constexpr Glyph {name}Glyphs[] = {{")
        for (offset, w, h, x, y, adv) in glyphs:
            parts.append(f"    {{{offset}, {w}, {h}, {x}, {y}, {adv}}},")
        parts.append("};")
        parts.append(
            f"inline constexpr Font {name} = {{{name}Glyphs, {name}Bits, {FIRST}, {LAST}, {ascent}, {descent}}};"
        )
        parts.append("")
    parts.append("}  // namespace omenu")
    OUT.write_text("\n".join(parts) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
